def t(key: str, lang: str = "en", **kwargs) -> str:
    """Return translated string, safely formatting arguments if present.

    Falls back to English, then to the raw key, so the app never crashes
    on a missing translation.
    """
    lang = (lang or "en").lower().strip()
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key, key)
    if kwargs and isinstance(text, str):
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text

def validate_translations() -> dict:
    """Return a report of missing / dirty translation keys (dev helper)."""
    en = set(TRANSLATIONS.get("en", {}).keys())
    fr = set(TRANSLATIONS.get("fr", {}).keys())
    return {
        "missing_in_fr": sorted(en - fr),
        "missing_in_en": sorted(fr - en),
        "dirty_lang_keys": [k for k in TRANSLATIONS if k != k.strip()],
        "dirty_keys": [
            f"{lang}: '{k}'"
            for lang, values in TRANSLATIONS.items()
            for k in values
            if k != k.strip()
        ],
    }

if __name__ == "__main__":
    report = validate_translations()
    for section, items in report.items():
        print(f"\n{section}:")
        print("  (none)" if not items else "\n".join(f"  - {i}" for i in items))